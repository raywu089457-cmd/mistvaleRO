function roFrame(c, def, x, y, scale, time, flip = false, progress = null) {
  const img = def && roImage(def.file);
  if (!img) return false;
  let index;
  if (progress !== null)
    index = Math.min(
      def.frames - 1,
      Math.floor(clamp(progress, 0, 0.999) * def.frames),
    );
  else {
    let ms = (time * 1000) % def.durations.reduce((s, n) => s + n, 0);
    index = 0;
    while (index < def.frames - 1 && ms > def.durations[index])
      ms -= def.durations[index++];
  }
  c.save();
  c.translate(x, y);
  if (flip) c.scale(-1, 1);
  c.drawImage(
    img,
    (def.ox || 0) + index * def.frameWidth,
    def.oy || 0,
    def.frameWidth,
    def.frameHeight,
    -def.anchor[0] * scale * (def.ks || 1),
    -def.anchor[1] * scale * (def.ks || 1),
    def.frameWidth * scale * (def.ks || 1),
    def.frameHeight * scale * (def.ks || 1),
  );
  c.restore();
  return true;
}
