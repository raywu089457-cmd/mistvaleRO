function roFacingFrame(states, state, direction) {
  const def = states[state] || states.idle || states.walk;
  const facing = def?.directions?.[direction];
  if (!facing) return def;
  // Job atlases keep every direction in one image (offsets ox/oy).
  if (facing.file === def.file) return facing;
  const src = RO.root + facing.file;
  if (RO.images[src]) {
    roDirectionCache.delete(src);
    roDirectionCache.set(src, true);
    return facing;
  }
  if (!roDirectionPending.has(src) && !RO.failed.includes(src)) {
    roDirectionPending.add(src);
    const im = new Image();
    im.onload = () => {
      RO.images[src] = im;
      roDirectionPending.delete(src);
      roDirectionCache.set(src, true);
      while (roDirectionCache.size > 64) {
        const oldest = roDirectionCache.keys().next().value;
        roDirectionCache.delete(oldest);
        delete RO.images[oldest];
      }
    };
    im.onerror = () => {
      roDirectionPending.delete(src);
      RO.failed.push(src);
    };
    im.src = src;
  }
  return def;
}
